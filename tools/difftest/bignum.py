"""Arithmetic on large numbers: the `bignum` cases (`run --bignum`).

The regressions, the cvc5 proofs and the fuzzer use small numbers, so no case
reaches the algorithms a big-number library uses only for large operands
(malachite's FFT multiplication starts at 390 64-bit words, 24,960 bits; GMP
has its own thresholds). These cases do. Each file declares the numeral and
rational literals and then defines terms such as

    (define t3 () (eo::mul A B) :is_eq C)

where C is computed here, exactly, with Python's integers and fractions. A
checker that computes a wrong value stops at that define with "Terms are not
equal", printing the value it computed. Each file ends with one define whose
expected value is wrong on purpose (the last digit changed), so that both
checkers print the full value of a large result and the harness compares it
byte for byte even when both are right.

The files are generated, deterministically (fixed seed), into
<work>/bignum, since they are several megabytes; GENERATOR_VERSION is part
of their content, so changing the generator changes the cases' cache keys.
"""

import random
import sys
from fractions import Fraction
from pathlib import Path

GENERATOR_VERSION = 1

# Operand sizes in bits: below, at and above the thresholds where the
# multiplication algorithms change (Karatsuba and Toom near a few thousand
# bits, malachite's FFT at 24,960 bits), and well above.
SIZES = [64, 1000, 4000, 12000, 24000, 24896, 24960, 25024, 26000, 50000,
         131072, 262144]

HEADER = """\
; Generated by tools/difftest/bignum.py (version {v}); do not edit.
(declare-const Int Type)
(declare-consts <numeral> Int)
(declare-const Real Type)
(declare-consts <rational> Real)
(declare-consts <decimal> Real)
(declare-const BitVec (-> Int Type))
(declare-consts <binary> (BitVec (eo::len eo::self)))
"""


def _z(n):
    return str(n)


def _q(f):
    f = Fraction(f)
    return f"{f.numerator}/{f.denominator}"


def _int(rng, bits, signed=True):
    n = rng.getrandbits(bits) | (1 << (bits - 1))  # exactly `bits` bits
    return -n if signed and rng.random() < 0.5 else n


def _bin(n, width):
    return "#b" + format(n, f"0{width}b") if width else "#b"


class _File:
    def __init__(self):
        self.lines = [HEADER.format(v=GENERATOR_VERSION)]
        self.count = 0

    def check(self, term, value):
        self.count += 1
        self.lines.append(f"(define t{self.count} () {term} :is_eq {value})")

    def wrong(self, term, value):
        """The deliberate failure at the end: `value` is a numeral, rational
        or string literal with its last digit changed."""
        i = max(j for j, c in enumerate(value) if c.isdigit())
        d = str((int(value[i]) + 1) % 10)
        self.check(term, value[:i] + d + value[i + 1:])

    def text(self):
        return "\n".join(self.lines) + "\n"


def _files(rng):
    files = {}

    f = _File()   # addition, negation, comparison
    for bits in SIZES:
        a, b = _int(rng, bits), _int(rng, bits)
        f.check(f"(eo::add {a} {b})", _z(a + b))
        f.check(f"(eo::neg {a})", _z(-a))
        f.check(f"(eo::add {a} {-a})", "0")
        f.check(f"(eo::gt {a} {b})", "true" if a > b else "false")
        f.check(f"(eo::is_neg {a})", "true" if a < 0 else "false")
    a, b = _int(rng, SIZES[-1]), _int(rng, SIZES[-1])
    f.wrong(f"(eo::add {a} {b})", _z(a + b))
    files["add"] = f

    f = _File()   # multiplication, balanced and unbalanced
    pairs = [(s, s) for s in SIZES] + [(SIZES[-1], 64), (SIZES[-1], 4000),
                                       (SIZES[-1], 26000), (50000, 25024)]
    for x, y in pairs:
        a, b = _int(rng, x), _int(rng, y)
        f.check(f"(eo::mul {a} {b})", _z(a * b))
        f.check(f"(eo::mul {a} {a})", _z(a * a))
    a, b = _int(rng, 1 << 20), _int(rng, 1 << 20)   # one product of 2^21 bits
    f.wrong(f"(eo::mul {a} {b})", _z(a * b))
    files["mul"] = f

    f = _File()   # powers
    for base, exp in [(10, 7500), (10, 21408), (10, 50000), (2, 100000),
                      (-3, 33333), (-7, 20000), (_int(rng, 3000, False), 10),
                      (_int(rng, 25000), 3), (_int(rng, 64), 2000)]:
        f.check(f"(eo::pow {base} {exp})", _z(base ** exp))
    f.wrong("(eo::pow 3 150000)", _z(3 ** 150000))
    files["pow"] = f

    f = _File()   # integer division and remainder, all four sign combinations
    for bits in SIZES:
        for sa, sb in [(1, 1), (-1, 1), (1, -1), (-1, -1)]:
            a = sa * _int(rng, 2 * bits, False)
            b = sb * _int(rng, bits, False)
            q, r = _euclid(a, b)
            f.check(f"(eo::zdiv {a} {b})", _z(q))
            f.check(f"(eo::zmod {a} {b})", _z(r))
    a, b = _int(rng, 2 * SIZES[-1]), _int(rng, SIZES[-1])
    f.wrong(f"(eo::zdiv {a} {b})", _z(_euclid(a, b)[0]))
    files["div"] = f

    f = _File()   # rationals: arithmetic, division, normalisation
    for bits in SIZES:
        x = Fraction(_int(rng, bits), _int(rng, bits, False))
        y = Fraction(_int(rng, bits), _int(rng, bits, False))
        f.check(f"(eo::add {_q(x)} {_q(y)})", _q(x + y))
        f.check(f"(eo::mul {_q(x)} {_q(y)})", _q(x * y))
        f.check(f"(eo::qdiv {_q(x)} {_q(y)})", _q(x / y))
        f.check(f"(eo::neg {_q(x)})", _q(-x))
        f.check(f"(eo::gt {_q(x)} {_q(y)})", "true" if x > y else "false")
        n, d = _int(rng, bits), _int(rng, bits, False)
        g = _int(rng, bits, False)
        f.check(f"(eo::qdiv {n * g} {d * g})", _q(Fraction(n, d)))
        f.check(f"(eo::to_z {_q(x)})", _z(x.numerator // x.denominator))
        f.check(f"(eo::to_q {n})", _q(n))
    x = Fraction(_int(rng, SIZES[-1]), _int(rng, SIZES[-1], False))
    y = Fraction(_int(rng, SIZES[-1]), _int(rng, SIZES[-1], False))
    f.wrong(f"(eo::mul {_q(x)} {_q(y)})", _q(x * y))
    files["rational"] = f

    f = _File()   # conversions between numerals, rationals, decimals and binaries
    for bits in SIZES:
        n = _int(rng, bits, False)
        whole, frac = str(_int(rng, bits, False)), str(_int(rng, bits, False))
        dec = Fraction(int(whole + frac), 10 ** len(frac))
        f.check(f"(eo::to_q {whole}.{frac})", _q(dec))
        f.check(f"(eo::to_z {whole}.{frac})", _z(dec.numerator // dec.denominator))
        f.check(f"(eo::to_z {_bin(n, bits)})", _z(n))
        f.check(f"(eo::to_bin {bits} {n})", _bin(n, bits))
        f.check(f"(eo::to_bin {bits + 7} {-n})", _bin((-n) % (1 << (bits + 7)), bits + 7))
        f.check(f"(eo::len {_bin(n, bits)})", _z(bits))
    n = _int(rng, SIZES[-1], False)
    f.wrong(f"(eo::to_z {_bin(n, SIZES[-1])})", _z(n))
    files["convert"] = f

    f = _File()   # bit-vector operations on wide binaries
    for bits in SIZES:
        a, b = _int(rng, bits, False), _int(rng, bits, False)
        m = (1 << bits) - 1
        A, B = _bin(a, bits), _bin(b, bits)
        f.check(f"(eo::and {A} {B})", _bin(a & b, bits))
        f.check(f"(eo::or {A} {B})", _bin(a | b, bits))
        f.check(f"(eo::xor {A} {B})", _bin(a ^ b, bits))
        f.check(f"(eo::not {A})", _bin(~a & m, bits))
        f.check(f"(eo::add {A} {B})", _bin((a + b) & m, bits))
        f.check(f"(eo::mul {A} {B})", _bin((a * b) & m, bits))
        f.check(f"(eo::concat {A} {B})", _bin((a << bits) | b, 2 * bits))
        lo, hi = bits // 3, 2 * bits // 3
        f.check(f"(eo::extract {A} {lo} {hi})", _bin((a >> lo) & ((1 << (hi - lo + 1)) - 1), hi - lo + 1))
    a, b = _int(rng, SIZES[-1], False), _int(rng, SIZES[-1], False)
    f.wrong(f"(eo::to_z (eo::mul {_bin(a, SIZES[-1])} {_bin(b, SIZES[-1])}))",
            _z((a * b) & ((1 << SIZES[-1]) - 1)))
    files["bitvec"] = f
    return files


def _euclid(a, b):
    """SMT-LIB's div and mod: the remainder is never negative."""
    q, r = divmod(a, b)
    if r < 0:
        q, r = q + 1, r - b
    return q, r


def generate(dest):
    """Writes the case files into `dest` (unless they are there already
    with the same content) and returns their paths, sorted."""
    sys.set_int_max_str_digits(0)   # the numbers have up to 600,000 digits
    dest = Path(dest)
    dest.mkdir(parents=True, exist_ok=True)
    paths = []
    for name, f in sorted(_files(random.Random(f"bignum/{GENERATOR_VERSION}")).items()):
        p = dest / f"{name}.eo"
        text = f.text()
        if not p.exists() or p.read_text() != text:
            p.write_text(text)
        paths.append(p)
    return paths
